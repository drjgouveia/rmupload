#!/usr/bin/env python3
"""Builds shared/reader.js from the Readability and DOMPurify sources embedded in the
"Read on reMarkable" extension's source maps, and copies it into each app.

    python3 tools/build_reader.py bfhkfdnddlhfippjbflipboognpdpoeh.zip
"""
import json
import pathlib
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = [
    ROOT / "shared/reader.js",
    ROOT / "RMUpload/Sources/RMUpload/Resources/reader.js",
    ROOT / "RMUploadAndroid/app/src/main/assets/reader.js",
    ROOT / "RMUploadDesktop/rmupload/reader.js",
]

# Runs inside the loaded page. `__rmuploadArticle()` returns JSON {title, html} for a
# standalone, print-ready article page, or null when the page has no readable article.
EXTRACT = r"""
var SR_ONLY = ["sr-only", "visually-hidden", "screen-reader-text"];

function article() {
  var parsed = new Readability(document.cloneNode(true), { classesToPreserve: SR_ONLY }).parse();
  if (!parsed || (parsed.textContent || "").trim().length < 200) return null;

  var clean = purify.sanitize(parsed.content || "", {
    ALLOW_DATA_ATTR: false,
    // Site-specific sizing on image containers leaves blank gaps in print.
    FORBID_ATTR: ["style"],
    FORBID_TAGS: ["iframe", "noscript", "template", "dialog"],
  });

  var doc = document.implementation.createHTMLDocument(parsed.title || document.title);
  if (parsed.lang) doc.documentElement.lang = parsed.lang;
  if (parsed.dir) doc.documentElement.dir = parsed.dir;
  var meta = doc.createElement("meta");
  meta.setAttribute("charset", "utf-8");
  doc.head.appendChild(meta);
  var style = doc.createElement("style");
  style.textContent = STYLE;
  doc.head.appendChild(style);

  var root = doc.createElement("article");
  var h1 = doc.createElement("h1");
  h1.textContent = parsed.title || document.title;
  root.appendChild(h1);
  var info = doc.createElement("p");
  info.className = "rm-meta";
  info.textContent = [parsed.byline, parsed.siteName, location.hostname]
    .filter(function (v, i, all) { return v && all.indexOf(v) === i; })
    .join(" · ");
  root.appendChild(info);
  var body = doc.createElement("div");
  body.innerHTML = clean;
  root.appendChild(body);
  doc.body.appendChild(root);

  // Many sites misuse screen-reader-only text, which would otherwise show up twice.
  doc.querySelectorAll(SR_ONLY.map(function (c) { return "." + c; }).join(",")).forEach(function (el) {
    el.remove();
  });
  // Off-screen print views never scroll, so lazy images would stay blank.
  doc.querySelectorAll("img").forEach(function (img) {
    img.removeAttribute("loading");
  });

  return JSON.stringify({
    title: h1.textContent,
    html: "<!doctype html>" + doc.documentElement.outerHTML,
  });
}

var STYLE = [
  "body { font-family: Georgia, 'Noto Serif', 'DejaVu Serif', serif; font-size: 13pt; line-height: 1.5; color: #000; margin: 0; }",
  "h1 { font-size: 22pt; line-height: 1.2; margin: 0 0 0.3em; }",
  "h2, h3, h4 { line-height: 1.25; break-after: avoid; }",
  ".rm-meta { font-family: sans-serif; font-size: 9.5pt; color: #444; border-bottom: 1px solid #999; padding-bottom: 0.6em; margin-bottom: 1.4em; }",
  "img, picture, video, svg { max-width: 100%; height: auto; display: block; margin: 0.6em auto; break-inside: avoid; }",
  "figure { margin: 1em 0; break-inside: avoid; }",
  "figcaption { font-size: 10pt; color: #444; text-align: center; }",
  "pre, code { font-family: monospace; font-size: 10pt; white-space: pre-wrap; overflow-wrap: anywhere; }",
  "blockquote { margin: 1em 0; padding-left: 1em; border-left: 3px solid #999; }",
  "table { border-collapse: collapse; max-width: 100%; }",
  "td, th { border: 1px solid #aaa; padding: 0.2em 0.4em; }",
  "a { color: inherit; text-decoration: none; }",
].join("\n");

window.__rmuploadArticle = function () {
  try {
    return article();
  } catch (e) {
    return null;
  }
};
"""


def main(zip_path: str) -> None:
    sources = {}
    with zipfile.ZipFile(zip_path) as z:
        for name in z.namelist():
            if not name.endswith(".map"):
                continue
            data = json.loads(z.read(name))
            for src, content in zip(data["sources"], data.get("sourcesContent") or []):
                if src.endswith("@mozilla/readability/Readability.js"):
                    sources["readability"] = content
                elif src.endswith("dompurify/dist/purify.es.mjs"):
                    sources["purify"] = content

    purify = "\n".join(
        line for line in sources["purify"].splitlines()
        if not line.startswith(("export ", "//# sourceMappingURL"))
    )
    script = "\n".join([
        "/* Generated by tools/build_reader.py from the Read on reMarkable extension's",
        " * bundled @mozilla/readability and DOMPurify (both Apache-2.0). Do not edit. */",
        "(function () {",
        "var module; // keep Readability from exporting as CommonJS",
        sources["readability"],
        purify,
        EXTRACT,
        "})();",
    ])
    for target in TARGETS:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(script)
        print(f"wrote {target.relative_to(ROOT)} ({len(script)} bytes)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "bfhkfdnddlhfippjbflipboognpdpoeh.zip"))
