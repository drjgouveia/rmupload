// swift-tools-version: 6.0

import PackageDescription

let package = Package(
    name: "RMUpload",
    platforms: [
        .iOS(.v17),
    ],
    products: [
        // An xtool project should contain exactly one library product,
        // representing the main app.
        .library(
            name: "RMUpload",
            targets: ["RMUpload"]
        ),
        // Share extension: hands shared webpages over to the app.
        .library(
            name: "RMUploadShare",
            targets: ["RMUploadShare"]
        ),
    ],
    targets: [
        .target(
            name: "RMUpload",
            // Generated by ../tools/build_reader.py (Readability + DOMPurify).
            resources: [.copy("Resources/reader.js")]
        ),
        .target(
            name: "RMUploadShare",
            swiftSettings: [.swiftLanguageMode(.v5)],
            // ShareViewController is only looked up by name at runtime; without -ObjC the
            // linker drops it, leaving an extension with no code (and zsign unable to sign it).
            linkerSettings: [.unsafeFlags(["-Xlinker", "-ObjC"])]
        ),
    ]
)
